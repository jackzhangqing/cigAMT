from __future__ import annotations

import argparse
import csv
import json
import random
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Callable

import numpy as np


DEFAULT_SOURCE_DIR = Path(__file__).resolve().parent
DEFAULT_OUTPUT_ROOT = Path(r"noise_data/Synthetic-Raw")
DEFAULT_LENGTHS = [100, 150, 200, 300, 400, 450, 500, 600, 750, 1000, 1500, 2048]

TYPE_NAMES = [
    "Pulse",
    "Quasi-Sinusoidal",
    "Square-wave",
    "Step-wave",
    "Triangular-wave",
    "Power-frequency",
    "White-noise",
    "Color-noise",
    "Harmonic",
    "Composite",
]


@dataclass(frozen=True)
class GenerationPlan:
    type_name: str
    length: int
    count: int


def safe_name(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", text)


def seed_everything(seed: int):
    random.seed(seed)
    np.random.seed(seed)


def add_generator_source(source_dir: Path):
    source = str(source_dir)
    if source not in sys.path:
        sys.path.insert(0, source)


def load_generators(source_dir: Path) -> dict[str, Callable[[int, int | None], np.ndarray | tuple[np.ndarray, dict[str, Any]]]]:
    add_generator_source(source_dir)

    from Color import pink_noise_1overf
    from Pluse import generate_sharp_pulse_noise
    from Power import powerline_noise
    from Quai_Sine import quasi_sine_noise
    from Square import generate_square_wave_noise
    from Step import generate_step_noise
    from White import gaussian_white_noise
    from Xiebo import generate_transient_oscillation_noise
    from tri import generate_tri_charge_noise

    def pulse(n: int, seed: int | None = None) -> np.ndarray:
        return generate_sharp_pulse_noise(
            n,
            mode="random",
            amp_range=(0.5, 5.0),
            return_meta=False,
            seed=seed,
        )

    def quasi_sinusoidal(n: int, seed: int | None = None) -> np.ndarray:
        if seed is not None:
            np.random.seed(seed)
        return quasi_sine_noise(n, A=float(np.random.uniform(0.5, 4.0)))

    def square_wave(n: int, seed: int | None = None) -> np.ndarray:
        return generate_square_wave_noise(
            n,
            mode="random",
            amp_range=(0.5, 4.0),
            return_meta=False,
            seed=seed,
        )

    def step_wave(n: int, seed: int | None = None) -> np.ndarray:
        return generate_step_noise(
            n,
            mode="random",
            A=float(np.random.uniform(1.0, 4.0)),
            amp_range=(0.5, 4.0),
            return_meta=False,
            seed=seed,
        )

    def triangular_wave(n: int, seed: int | None = None) -> np.ndarray:
        return generate_tri_charge_noise(
            n,
            mode="random",
            event_range=(1, 5),
            amp_range=(0.5, 4.0),
            return_meta=False,
            seed=seed,
        )

    def power_frequency(n: int, seed: int | None = None) -> np.ndarray:
        if seed is not None:
            np.random.seed(seed)
        return powerline_noise(n, A=float(np.random.uniform(0.5, 4.0)))

    def white_noise(n: int, seed: int | None = None) -> np.ndarray:
        return gaussian_white_noise(
            n,
            amp_range=(0.2, 4.0),
            use_random_amp=True,
            return_meta=False,
            seed=seed,
        )

    def color_noise(n: int, seed: int | None = None) -> np.ndarray:
        if seed is not None:
            np.random.seed(seed)
        return pink_noise_1overf(n=n, A=float(np.random.uniform(0.2, 4.0)))

    def harmonic(n: int, seed: int | None = None) -> np.ndarray:
        return generate_transient_oscillation_noise(
            n,
            mode="random",
            event_range=(1, 5),
            amp_range=(0.5, 5.0),
            return_meta=False,
            seed=seed,
        )

    base_generators: dict[str, Callable[[int, int | None], np.ndarray]] = {
        "Pulse": pulse,
        "Quasi-Sinusoidal": quasi_sinusoidal,
        "Square-wave": square_wave,
        "Step-wave": step_wave,
        "Triangular-wave": triangular_wave,
        "Power-frequency": power_frequency,
        "White-noise": white_noise,
        "Color-noise": color_noise,
        "Harmonic": harmonic,
    }

    def composite(n: int, seed: int | None = None) -> tuple[np.ndarray, dict[str, Any]]:
        """Notebook-compatible composite noise, generalized from n=1500 to any n."""
        if seed is not None:
            np.random.seed(seed)

        component_generators: dict[str, Callable[[], np.ndarray]] = {
            "tri_charge": lambda: generate_tri_charge_noise(
                n=n,
                fs=150,
                mode="random",
                event_range=(2, 5),
                return_meta=False,
            ),
            "sharp_pulse": lambda: generate_sharp_pulse_noise(
                n=n,
                fs=150,
                mode="random",
                pulse_range=(5, 12),
                W_range=(1, 4),
                single_point_prob=0.7,
                min_gap=20,
                return_meta=False,
            ),
            "ringing": lambda: generate_transient_oscillation_noise(
                n=n,
                fs=150,
                mode="random",
                event_range=(2, 4),
                amp_range=(1.0, 5.0),
                width_ratio_range=(0.04, 0.12),
                cycles_range=(3, 12),
                min_gap=40,
                return_meta=False,
            ),
            "powerline": lambda: powerline_noise(n=n, fs=150, A=3.0),
            "quasi_sine": lambda: quasi_sine_noise(n=n, A=3.0),
            "square": lambda: generate_square_wave_noise(
                n=n,
                fs=150,
                mode="random",
                amp_range=(1.0, 3.0),
                return_meta=False,
            ),
            "step": lambda: generate_step_noise(
                n=n,
                fs=150,
                mode="random",
                A=3.0,
                return_meta=False,
            ),
            "white": lambda: gaussian_white_noise(
                n=n,
                fs=150,
                amp_range=(0.2, 5.0),
                use_random_amp=True,
                return_meta=False,
            ),
            "pink": lambda: pink_noise_1overf(
                n=n,
                fs=150,
                A=3.0,
                return_meta=False,
            ),
        }

        all_types = list(component_generators)
        component_num = int(np.random.randint(2, min(5, len(all_types)) + 1))
        selected = list(np.random.choice(all_types, size=component_num, replace=False))

        components = []
        component_rms = []
        for type_name in selected:
            component = np.asarray(component_generators[type_name](), dtype=np.float32)
            component = component - float(np.mean(component))
            rms = float(np.sqrt(np.mean(component * component)))
            component_rms.append(rms)
            if rms > 1e-8:
                component = component / rms
            components.append(component)

        weights = np.random.dirichlet(np.ones(component_num))
        y = np.zeros(n, dtype=np.float32)
        for weight, component in zip(weights, components):
            y += float(weight) * component

        total_amp = 10 ** np.random.uniform(np.log10(1.0), np.log10(5.0))  # 整体赋值缩放
        meta = {
            "composite_components": selected,
            "composite_weights": [float(w) for w in weights],
            "composite_component_rms": component_rms,
            "composite_num_components": int(component_num),
            "composite_total_amp": float(total_amp),
        }

        '''
        1. 每个基础分量先 RMS 归一化
        2. 用 Dirichlet 权重混合
        3. 最后用 total_amp 控制整体强度
        训练用的是 Synthetic-Norm，模型学的是形态；如果训练用 Synthetic-Raw，模型才会学到强弱幅值。
        '''
        return (total_amp * y).astype(np.float32, copy=False), meta  # 让其返回复合波形的组成

    return {**base_generators, "Composite": composite}


def split_generated(result: np.ndarray | tuple[np.ndarray, dict[str, Any]]) -> tuple[np.ndarray, dict[str, Any]]:
    if isinstance(result, tuple):
        x, meta = result
        return np.asarray(x), dict(meta)
    return np.asarray(result), {}


def normalize_sample(x: np.ndarray, mode: str) -> np.ndarray:
    x = np.asarray(x, dtype=np.float32).reshape(-1)
    x = np.nan_to_num(x, nan=0.0, posinf=0.0, neginf=0.0)

    if mode == "none":
        return x

    if mode == "rms":
        x = x - float(np.mean(x))
        rms = float(np.sqrt(np.mean(x * x)))
        if rms > 1e-8:
            x = x / rms
        return x.astype(np.float32, copy=False)

    if mode == "maxabs":
        maxabs = float(np.max(np.abs(x)))
        if maxabs > 1e-8:
            x = x / maxabs
        return x.astype(np.float32, copy=False)

    raise ValueError(f"Unknown normalize mode: {mode}")


def sample_stats(x: np.ndarray) -> dict[str, float]:
    x = np.asarray(x, dtype=np.float32).reshape(-1)
    if x.size == 0:
        return {"max_abs": 0.0, "avg_abs": 0.0, "rms": 0.0}
    return {
        "max_abs": float(np.max(np.abs(x))),
        "avg_abs": float(np.mean(np.abs(x))),
        "rms": float(np.sqrt(np.mean(x * x))),
    }


def get_length_weights(type_name: str, lengths: list[int]) -> np.ndarray:
    weights = np.ones(len(lengths), dtype=np.float64)

    def set_weight(length_values: list[int], value: float):
        for length_value in length_values:
            if length_value in lengths:
                weights[lengths.index(length_value)] = value

    if type_name == "Pulse":
        weights *= 0.6
        set_weight([100, 150, 200, 300, 400, 450, 500], 2.0)
        set_weight([600, 750, 1000], 1.2)
        set_weight([1500, 2048], 0.4)
    elif type_name in {"Power-frequency", "White-noise", "Color-noise"}:
        weights *= 0.5
        set_weight([1000, 1500, 2048], 2.0)
        set_weight([500, 600, 750], 1.0)
        set_weight([100, 150, 200, 300], 0.25)
    elif type_name in {"Square-wave", "Step-wave", "Quasi-Sinusoidal"}:
        weights *= 0.8
        set_weight([300, 400, 450, 500, 600, 750, 1000, 1500, 2048], 1.4)
        set_weight([100, 150], 0.4)
    elif type_name in {"Triangular-wave", "Harmonic"}:
        weights *= 0.8
        set_weight([200, 300, 400, 450, 500, 600, 750, 1000, 1500], 1.4)
        set_weight([2048], 0.9)
    elif type_name == "Composite":
        weights *= 0.7
        set_weight([500, 600, 750, 1000, 1500, 2048], 1.8)
        set_weight([100, 150, 200], 0.25)

    weights = weights / weights.sum()
    return weights


def build_plan(
    per_type: int,
    lengths: list[int],
    distribution: str,
) -> list[GenerationPlan]:
    plans: list[GenerationPlan] = []
    for type_name in TYPE_NAMES:
        if distribution == "uniform":
            base = per_type // len(lengths)
            counts = np.full(len(lengths), base, dtype=int)
            counts[: per_type - int(counts.sum())] += 1
        elif distribution == "type-aware":
            weights = get_length_weights(type_name, lengths)
            counts = np.floor(weights * per_type).astype(int)
            remainder = per_type - int(counts.sum())
            if remainder > 0:
                order = np.argsort(-(weights * per_type - counts))
                counts[order[:remainder]] += 1
        else:
            raise ValueError(f"Unknown distribution: {distribution}")

        for length, count in zip(lengths, counts):
            if count > 0:
                plans.append(GenerationPlan(type_name=type_name, length=length, count=int(count)))
    return plans


def save_manifest(manifest_rows: list[dict[str, object]], manifest_path: Path):
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = [
        "path",
        "type_name",
        "type_id",
        "length",
        "length_ratio",
        "source_id",
        "sample_id",
        "seed",
        "raw_path",
        "raw_max_abs",
        "raw_avg_abs",
        "raw_rms",
        "max_abs",
        "avg_abs",
        "rms",
        "composite_components",
        "composite_weights",
        "composite_component_rms",
        "composite_num_components",
        "composite_total_amp",
    ]
    with manifest_path.open("w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(manifest_rows)


def write_dataset_info(output_root: Path, args: argparse.Namespace, plans: list[GenerationPlan]):
    info = {
        "type_names": TYPE_NAMES,
        "type_to_id": {name: idx for idx, name in enumerate(TYPE_NAMES)},
        "lengths": args.lengths,
        "per_type": args.per_type,
        "distribution": args.distribution,
        "normalize": args.normalize,
        "fs": args.fs,
        "seed": args.seed,
        "source_id": 1,
        "source_name": "synthetic",
        "plan": [
            {"type_name": p.type_name, "length": p.length, "count": p.count}
            for p in plans
        ],
    }
    with (output_root / "dataset_info.json").open("w", encoding="utf-8") as f:
        json.dump(info, f, indent=2, ensure_ascii=False)


def generate_dataset(args: argparse.Namespace):
    source_dir = Path(args.source_dir)
    output_root = Path(args.output_root)
    output_root.mkdir(parents=True, exist_ok=True)
    raw_output_root = Path(args.raw_output_root) if args.raw_output_root else None


    if args.save_raw_copy and raw_output_root is None:  # save_raw_copy is true  raw_output_root is None
        raw_output_root = output_root.with_name(output_root.name + "-raw")

    #  默认raw_output_root is None
    if raw_output_root is not None:
        raw_output_root.mkdir(parents=True, exist_ok=True)

    seed_everything(args.seed)
    generators = load_generators(source_dir)
    plans = build_plan(args.per_type, args.lengths, args.distribution)
    type_to_id = {name: idx for idx, name in enumerate(TYPE_NAMES)}

    manifest_rows: list[dict[str, object]] = []
    global_id = int(args.start_index)
    for plan in plans:
        generator = generators[plan.type_name]
        target_dir = output_root / f"Synthetic-Len{plan.length}" / plan.type_name
        target_dir.mkdir(parents=True, exist_ok=True)
        raw_target_dir = None
        if raw_output_root is not None:
            raw_target_dir = raw_output_root / f"Synthetic-Len{plan.length}" / plan.type_name
            raw_target_dir.mkdir(parents=True, exist_ok=True)

        for _ in range(plan.count):
            sample_seed = args.seed + global_id * 17
            generated, generation_meta = split_generated(generator(plan.length, sample_seed))
            raw_x = np.asarray(generated, dtype=np.float32).reshape(-1)
            raw_x = np.nan_to_num(raw_x, nan=0.0, posinf=0.0, neginf=0.0)
            raw_stats = sample_stats(raw_x)
            x = normalize_sample(raw_x, args.normalize)
            stats = sample_stats(x)

            name = (
                f"syn_{safe_name(plan.type_name)}_id{global_id:07d}"
                f"_len{plan.length}_max{stats['max_abs']:.3f}_avg{stats['avg_abs']:.3f}.npy"
            )
            path = target_dir / name
            if path.exists() and not args.overwrite:
                raise FileExistsError(f"Output exists: {path}")
            np.save(path, x.astype(np.float32, copy=False))

            # 保存未rms归一化的结果
            raw_path = ""
            if raw_target_dir is not None:
                raw_name = (
                    f"syn_{safe_name(plan.type_name)}_id{global_id:07d}"
                    f"_len{plan.length}_rawmax{raw_stats['max_abs']:.3f}"
                    f"_rawavg{raw_stats['avg_abs']:.3f}.npy"
                )
                raw_path_obj = raw_target_dir / raw_name
                if raw_path_obj.exists() and not args.overwrite:
                    raise FileExistsError(f"Output exists: {raw_path_obj}")
                np.save(raw_path_obj, raw_x.astype(np.float32, copy=False))
                raw_path = str(raw_path_obj)

            manifest_rows.append(
                {
                    "path": str(path),
                    "type_name": plan.type_name,
                    "type_id": type_to_id[plan.type_name],
                    "length": plan.length,
                    "length_ratio": plan.length / 2048.0,
                    "source_id": 1,
                    "sample_id": global_id,
                    "seed": sample_seed,
                    "raw_path": raw_path,
                    "raw_max_abs": f"{raw_stats['max_abs']:.6g}",
                    "raw_avg_abs": f"{raw_stats['avg_abs']:.6g}",
                    "raw_rms": f"{raw_stats['rms']:.6g}",
                    "max_abs": f"{stats['max_abs']:.6g}",
                    "avg_abs": f"{stats['avg_abs']:.6g}",
                    "rms": f"{stats['rms']:.6g}",
                    "composite_components": "|".join(generation_meta.get("composite_components", [])),
                    "composite_weights": "|".join(
                        f"{w:.6g}" for w in generation_meta.get("composite_weights", [])
                    ),
                    "composite_component_rms": "|".join(
                        f"{r:.6g}" for r in generation_meta.get("composite_component_rms", [])
                    ),
                    "composite_num_components": generation_meta.get("composite_num_components", ""),
                    "composite_total_amp": (
                        f"{generation_meta['composite_total_amp']:.6g}"
                        if "composite_total_amp" in generation_meta
                        else ""
                    ),
                }
            )
            global_id += 1

        print(f"Generated {plan.count:5d} | {plan.type_name:18s} | len={plan.length}")

    manifest_path = output_root / "synthetic_manifest.csv"
    save_manifest(manifest_rows, manifest_path)
    write_dataset_info(output_root, args, plans)
    print(f"\nSaved samples: {len(manifest_rows)}")
    print(f"Output root: {output_root}")
    if raw_output_root is not None:
        print(f"Raw copy root: {raw_output_root}")
    print(f"Manifest: {manifest_path}")
    print(f"Dataset info: {output_root / 'dataset_info.json'}")


def parse_lengths(text: str) -> list[int]:
    lengths = [int(part.strip()) for part in text.split(",") if part.strip()]
    if not lengths:
        raise argparse.ArgumentTypeError("At least one length is required.")
    return sorted(set(lengths))


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Generate synthetic AMT noise npy files.")
    parser.add_argument("--source-dir", default=str(DEFAULT_SOURCE_DIR))
    parser.add_argument("--output-root", default=str(DEFAULT_OUTPUT_ROOT))

    parser.add_argument("--per-type", type=int, default=2000)

    parser.add_argument("--lengths", type=parse_lengths, default=DEFAULT_LENGTHS)

    parser.add_argument("--distribution", choices=["type-aware", "uniform"], default="type-aware")

    parser.add_argument("--normalize", choices=["rms", "maxabs", "none"], default="rms")

    parser.add_argument(
        "--save-raw-copy",
        action="store_true",
        help="Also save the unnormalized generated sample.",
    )
    parser.add_argument(
        "--raw-output-root",
        default=None,
        help="Where to save raw copies. Default with --save-raw-copy: <output-root>-raw.",
    )
    parser.add_argument("--fs", type=float, default=150.0)
    parser.add_argument("--seed", type=int, default=20260707)
    parser.add_argument("--start-index", type=int, default=0)
    parser.add_argument("--overwrite", action="store_true")
    return parser


def main():
    parser = build_parser()
    args = parser.parse_args()
    generate_dataset(args)


if __name__ == "__main__":
    main()
